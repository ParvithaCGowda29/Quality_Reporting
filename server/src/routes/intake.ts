// Data Intake skill: upload -> virus-scan stub -> store/index -> parse -> missing-data check.
import path from 'node:path'
import fs from 'node:fs'
import { Router } from 'express'
import multer from 'multer'
import { db } from '../db.ts'
import { audit } from '../audit.ts'
import { config } from '../config.ts'
import { evaluateChecklist, setConfirmation } from '../domain/checklist.ts'
import { addOperation } from '../domain/pfdEngine.ts'
import { parseWorkbook } from '../intakeParse.ts'
import { actor } from './projects.ts'
import type { IntakeDocument } from '../types.ts'

const upload = multer({ dest: path.join(config.dataDir, 'uploads'), limits: { fileSize: 50 * 1024 * 1024 } })
export const intake = Router()

intake.post('/:projectId/documents', upload.single('file'), async (req, res, next) => {
  try {
    const projectId = req.params.projectId
    if (!db.get('projects', projectId)) return res.status(404).json({ error: 'project not found' })
    if (!req.file) return res.status(400).json({ error: 'file field is required' })
    // Virus-scan hook: placeholder for ClamAV / cloud scan. Blocks executable-ish uploads.
    if (/\.(exe|bat|sh|cmd|js)$/i.test(req.file.originalname)) {
      fs.unlinkSync(req.file.path)
      return res.status(422).json({ error: 'file type blocked by scan policy' })
    }
    const doc: IntakeDocument = {
      id: db.newId(),
      projectId,
      kind: req.body.kind ?? 'other',
      filename: req.file.originalname,
      storedPath: req.file.path,
      byteSize: req.file.size,
      uploadedBy: actor(req),
      uploadedAt: new Date().toISOString(),
      scanStatus: 'clean',
      parseStatus: 'pending',
    }
    db.insert('documents', doc)
    audit(projectId, actor(req), 'intake.uploaded', `${doc.filename} (${doc.kind})`)

    // Auto-parse PFD/PFMEA Excel into structured process data.
    if (/\.xlsx?$/i.test(doc.filename)) {
      try {
        const parsed = await parseWorkbook(doc.storedPath)
        if (parsed.kind === 'pfd') {
          for (const op of parsed.operations) addOperation(projectId, op.description, { opNo: op.opNo })
          doc.parseSummary = `PFD: captured ${parsed.operations.length} operations into process data`
        } else if (parsed.kind === 'pfmea') {
          doc.parseSummary = `PFMEA: read ${parsed.rows.length} existing failure rows (kept as reference; drafts are generated by the PFMEA skill)`
        } else {
          doc.parseSummary = parsed.note
        }
        doc.parseStatus = 'parsed'
      } catch (e: any) {
        doc.parseStatus = 'failed'
        doc.parseSummary = `parse failed: ${e.message}`
      }
      db.update<IntakeDocument>('documents', doc.id, { parseStatus: doc.parseStatus, parseSummary: doc.parseSummary })
      audit(projectId, actor(req), 'intake.parsed', doc.parseSummary ?? '')
    }
    res.status(201).json({ document: doc, checklist: evaluateChecklist(projectId) })
  } catch (e) { next(e) }
})

intake.get('/:projectId/documents', (req, res) => {
  res.json(db.where<IntakeDocument>('documents', d => d.projectId === req.params.projectId))
})

intake.get('/:projectId/checklist', (req, res) => {
  const items = evaluateChecklist(req.params.projectId)
  const missing = items.filter(i => !i.satisfied)
  res.json({ items, missing, halt: missing.length > 0, note: missing.length ? 'Missing-data check: halt and notify the quality manager on gaps.' : 'All required items present.' })
})

// Non-document checklist items (agreements, access grants) are confirmed explicitly.
intake.post('/:projectId/checklist/confirm', (req, res, next) => {
  try {
    const items = setConfirmation(req.params.projectId, req.body?.key, req.body?.confirmed !== false)
    audit(req.params.projectId, actor(req), 'intake.checklist-confirmed', `${req.body?.key}=${req.body?.confirmed !== false}`)
    res.json({ items, missing: items.filter(i => !i.satisfied) })
  } catch (e) { next(e) }
})
